export function getUpgradeCost(upgrade: UpgradeItem, currentLevel: number): number {
  if (currentLevel >= upgrade.maxLevel) return Infinity;
  return Math.round(upgrade.baseCost * Math.pow(upgrade.costMultiplier, currentLevel));
}

export function formatCompactNumber(num: number): string {
  if (num === Infinity) return 'MAX';
  if (num >= 1_000_000_000_000_000_000) return `$${(num / 1_000_000_000_000_000_000).toFixed(1)}Q`;
  if (num >= 1_000_000_000_000) return `$${(num / 1_000_000_000_000).toFixed(1)}T`;
  if (num >= 1_000_000_000) return `$${(num / 1_000_000_000).toFixed(1)}B`;
  if (num >= 1_000_000) return `$${(num / 1_000_000).toFixed(1)}M`;
  if (num >= 1_000) return `$${(num / 1_000).toFixed(0)}K`;
  return `$${num.toLocaleString()}`;
}

export function getShiftThreshold(prestigeCount: number): number {
  const thresholds = [10_000, 100_000, 10_000_000, 1_000_000_000, 100_000_000_000];
  return thresholds[Math.min(prestigeCount, thresholds.length - 1)];
}

export const PRESTIGE_COST = 10_000; // Starting shift threshold

export function calculatePPGained(lifetimeCredits: number, prestigeCount: number): number {
  const base = Math.max(5, Math.floor(Math.sqrt(Math.max(0, lifetimeCredits) / 5_000)));
  return Math.max(5, base + prestigeCount * 5);
}

